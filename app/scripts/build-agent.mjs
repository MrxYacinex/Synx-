// Bundles src/agent/agent.ts into a self-contained string the app injects into the WebView.
// Run: npm run build:agent  (also runs automatically before `npm start`).
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [resolve(root, 'src/agent/agent.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  target: ['safari13', 'chrome70'],
  minify: process.argv.includes('--minify'),
  legalComments: 'none',
});
const code = result.outputFiles[0].text;
const out = resolve(root, 'src/agent/agentSource.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-agent.mjs from src/agent/agent.ts. Do not edit.\n` +
    `export const AGENT_SOURCE: string = ${JSON.stringify(code)};\n`,
);
// Plain JS copy for browser tests.
writeFileSync(resolve(root, 'src/agent/agent.generated.js'), code);
console.log(`[synx] agent bundled (${(code.length / 1024).toFixed(1)} KB)`);
